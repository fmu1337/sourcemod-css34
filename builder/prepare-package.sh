#!/usr/bin/env bash
set -euo pipefail

PACKAGE_DIR="${1:?package directory required}"
SOURCEMOD_DIR="${2:?sourcemod directory required}"
BUILDER_DIR="${3:?builder directory required}"
DEPS_DIR="${4:-$(cd "$BUILDER_DIR/.." && pwd)/deps}"

SM_ROOT="$PACKAGE_DIR/addons/sourcemod"
GAMEDATA_ROOT="$SM_ROOT/gamedata"
TRANSLATIONS_REF="${TRANSLATIONS_REF:-master}"

echo "==> Stripping Linux binaries"
if [ "${BUILD_PLATFORM:-linux}" != "windows" ]; then
  while IFS= read -r -d '' binary; do
    strip --strip-unneeded "$binary"
  done < <(find "$SM_ROOT/bin" "$SM_ROOT/extensions" -type f \( -name '*.so' -o -name 'spcomp' \) -print0)
fi

echo "==> Installing self-contained CS:S v34 gamedata"
# CS:S v34 has a fixed engine ABI. Do not inherit gamedata from a current
# SourceMod build: it also carries entries for newer Source branches and can
# silently change this package's runtime contract.
rm -rf "$GAMEDATA_ROOT"
mkdir -p "$GAMEDATA_ROOT"
cp -a "$BUILDER_DIR/assets/gamedata/." "$GAMEDATA_ROOT/"

python3 "$BUILDER_DIR/../testing/scripts/check-css34-gamedata.py" \
  "$GAMEDATA_ROOT" --source "$SOURCEMOD_DIR"

echo "==> Patching core.cfg for CS:S v34 release layout"
core_cfg="$SM_ROOT/configs/core.cfg"
if [ -f "$core_cfg" ]; then
  sed -i 's/^\(\s*"DisableAutoUpdate"\s*\)"no"/\1"yes"/' "$core_cfg"
fi

# SM 1.12+ geoip.ext looks for any *.mmdb under configs/geoip (legacy GeoIP.dat
# is not enough). Official SM also omits the DB; ship GeoLite2-Country for css34.
geoip_cfg="$SM_ROOT/configs/geoip"
if [ -f "$SM_ROOT/extensions/geoip.ext.so" ] || [ -f "$SM_ROOT/extensions/geoip.ext.dll" ]; then
  mkdir -p "$geoip_cfg"
  shopt -s nullglob
  mmdbs=("$geoip_cfg"/*.mmdb)
  shopt -u nullglob
  if [ "${#mmdbs[@]}" -eq 0 ]; then
    echo "==> Fetching GeoLite2-Country.mmdb for geoip.ext"
    chmod +x "$BUILDER_DIR/download-geolite2.sh"
    CACHE_DIR="${CACHE_DIR:-$DEPS_DIR}" "$BUILDER_DIR/download-geolite2.sh" "$geoip_cfg"
  fi
  # download-geolite2.sh stages via mktemp (mode 0600): srcds running as a
  # non-root user could not read the DB after `tar -x` as root.
  chmod 0644 "$geoip_cfg"/*.mmdb
fi

echo "==> Fetching upstream translations"
translations_dir="$DEPS_DIR/sourcemod-translations"
rm -rf "$translations_dir"
git clone --depth 1 --filter=blob:none --sparse \
  https://github.com/alliedmodders/sourcemod "$translations_dir"
git -C "$translations_dir" sparse-checkout set translations
if [ "$TRANSLATIONS_REF" != "master" ]; then
  git -C "$translations_dir" fetch --depth 1 origin "$TRANSLATIONS_REF"
  git -C "$translations_dir" checkout "$TRANSLATIONS_REF"
fi

rm -rf "$SM_ROOT/translations"
cp -a "$translations_dir/translations" "$SM_ROOT/translations"

if [ ! -f "$SM_ROOT/scripting/include/version_auto.inc" ]; then
  inc_dir="$SOURCEMOD_DIR/build/includes"
  if [ -f "$inc_dir/version_auto.inc" ]; then
    cp -f "$inc_dir/version_auto.inc" "$SM_ROOT/scripting/include/version_auto.inc"
  else
    echo "warning: version_auto.inc was not generated by the build" >&2
  fi
fi

echo "==> Package prepared"
